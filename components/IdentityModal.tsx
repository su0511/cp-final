"use client";

import React from 'react';
import { usePalette } from '@/context/PaletteContext';
import { motion } from 'framer-motion';

export default function IdentityModal({ onClose }: { onClose: () => void }) {
  const { mixedColor, mixAnalysis, savedArtifacts } = usePalette();

  return (
    <motion.div 
      className="fixed inset-0 z-[9999] flex items-center justify-center bg-black/80 backdrop-blur-sm"
      initial={{ opacity: 0 }}
      animate={{ opacity: 1 }}
      exit={{ opacity: 0 }}
      onClick={onClose}
    >
      <motion.div 
        className="bg-white w-[400px] max-w-[90vw] overflow-hidden shadow-2xl relative"
        initial={{ scale: 0.9, y: 50 }}
        animate={{ scale: 1, y: 0 }}
        onClick={(e) => e.stopPropagation()} // Prevent closing when clicking card
      >
        {/* Top Color Block */}
        <div 
          className="h-[300px] w-full relative flex items-center justify-center"
          style={{ backgroundColor: mixedColor }}
        >
          {/* Hex Code */}
          <span className="font-mono text-white/50 text-4xl font-bold tracking-widest mix-blend-overlay">
            {mixedColor}
          </span>
        </div>

        {/* Info Section */}
        <div className="p-8">
          <h2 className="text-3xl font-bold mb-2 text-black uppercase tracking-tight leading-none">
            {mixAnalysis.era}
          </h2>
          <p className="font-mono text-sm text-gray-600 mb-6 italic">
            "{mixAnalysis.poem}"
          </p>
          
          <div className="grid grid-cols-2 gap-4 text-xs font-mono text-gray-500 mb-6 border-b border-gray-100 pb-6 mt-4">
            <div>
              <span className="block text-gray-400 text-[10px] mb-1">AESTHETIC AGE</span>
              <span className="text-black text-xl font-bold">
                {mixAnalysis.averageYear === 0 
                  ? 'Unknown' 
                  : mixAnalysis.averageYear > 0 
                    ? `${mixAnalysis.averageYear} AD` 
                    : `${Math.abs(mixAnalysis.averageYear)} BC`}
              </span>
            </div>
            <div>
              <span className="block text-gray-400 text-[10px] mb-1">SAMPLES MIXED</span>
              <span className="text-black text-xl font-bold">{savedArtifacts.length}</span>
            </div>
          </div>

          {/* Ingredients List */}
          <div className="flex gap-4">
            <div className="flex-1">
              <span className="block text-gray-400 text-[10px] mb-2 font-mono uppercase">Source Colors</span>
              <div className="flex gap-1 overflow-x-auto pb-2 no-scrollbar">
                {savedArtifacts.map(art => (
                  <div 
                    key={`color-${art.id}`}
                    className="w-6 h-8 flex-shrink-0 rounded-sm" 
                    style={{ backgroundColor: art.hex }}
                    title={art.colorName}
                  />
                ))}
              </div>
            </div>

            <div className="flex-1">
              <span className="block text-gray-400 text-[10px] mb-2 font-mono uppercase">Source Artifacts</span>
              <div className="flex gap-1 overflow-x-auto pb-2 no-scrollbar">
                {savedArtifacts.map(art => (
                  <div 
                    key={`img-${art.id}`}
                    className="w-6 h-8 flex-shrink-0 rounded-sm overflow-hidden bg-gray-100"
                    title={art.title}
                  >
                    <img 
                      src={art.imageUrl} 
                      alt={art.title} 
                      className="w-full h-full object-cover"
                    />
                  </div>
                ))}
              </div>
            </div>
          </div>
          
          <p className="text-[10px] text-gray-300 mt-6 text-center uppercase tracking-widest font-mono">
            Generated by The Met Palette
          </p>
        </div>
        
        {/* Close Button */}
        <button 
          onClick={onClose}
          className="absolute top-4 right-4 text-white/50 hover:text-white transition-colors w-8 h-8 flex items-center justify-center rounded-full hover:bg-white/10"
        >
          ✕
        </button>
      </motion.div>
    </motion.div>
  );
}

